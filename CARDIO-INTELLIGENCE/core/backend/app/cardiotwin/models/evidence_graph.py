class EvidenceNodeMetadata(BaseModel):
    """Metadata for an evidence node."""

    node_type: EvidenceNodeType = Field(default=..., description="Type of evidence node")

    # Temporal information
    observation_time: datetime | None = Field(
        default=None,
        description="When the evidence was observed/collected"
    )
    valid_from: datetime | None = Field(
        default=None,
        description="Start of validity window"
    )
    valid_to: datetime | None = Field(
        default=None,
        description="End of validity window"
    )

    # Source information
    source: str = Field(default="", description="Source of the evidence")
    source_id: str | None = Field(default=None, description="Source identifier")

    # Quality and confidence
    confidence: float = Field(default=0.0, ge=0.0, le=1.0, description="Confidence score (0-1)")
    quality_score: float = Field(default=1.0, ge=0.0, le=1.0, description="Quality score (0-1)")

    # Provenance
    provenance: str = Field(default="", description="Provenance category")

    # Clinical relevance
    clinical_relevance: float = Field(default=1.0, ge=0.0, le=1.0, description="Clinical relevance (0-1)")

    # Versioning
    version: int = Field(default=1, ge=1, description="Node version")
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="When the node was created"
    )
    updated_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="When the node was last updated"
    )

    # Additional metadata
    tags: list[str] = Field(default_factory=list, description="Node tags")
    custom_metadata: dict[str, Any] = Field(default_factory=dict, description="Custom metadata")


class EvidenceNode(BaseModel):
    """A node in the evidence graph representing a single piece of evidence.

    Each node represents a discrete piece of evidence such as:
    - A clinical observation (blood pressure, heart rate)
    - An ECG study
    - An imaging study (CMR, Echo, etc.)
    - A diagnostic report
    - A model inference/prediction
    - A digital twin instance
    - An agent execution
    - A clinical review

    Nodes are connected by EvidenceEdges that define their relationships.
    """

    id: UUID = Field(default_factory=uuid4, description="Unique node identifier")

    # Entity reference (links to domain model entities)
    cardiac_case_id: UUID = Field(default=..., description="Reference to CardiacCase")
    entity_type: str = Field(default=..., description="Type of domain entity (ECGStudy, ImagingStudy, etc.)")
    entity_id: UUID = Field(default=..., description="Reference to the actual domain entity")

    # Node data
    data: dict[str, Any] = Field(default_factory=dict, description="Evidence data payload")
    summary: str = Field(default="", description="Human-readable summary of the evidence")

    # Metadata
    metadata: EvidenceNodeMetadata = Field(
        default_factory=EvidenceNodeMetadata,
        description="Node metadata"
    )

    # Computed properties (not stored, derived)
    degree: int = Field(default=0, description="Number of connections to this node")
    in_degree: int = Field(default=0, description="Number of incoming connections")
    out_degree: int = Field(default=0, description="Number of outgoing connections")

    # Validation
    @model_validator(mode='after')
    def validate_metadata_consistency(self) -> EvidenceNode:
        """Ensure metadata is consistent with node type."""
        return self


class EvidenceEdgeMetadata(BaseModel):
    """Metadata for an evidence edge (relationship between nodes)."""

    relationship: EvidenceRelationship = Field(default=..., description="Type of relationship")

    # Consistency information
    consistency_status: ConsistencyStatus = Field(
        default=ConsistencyStatus.UNRESOLVED,
        description="Consistency status of this relationship"
    )
    consistency_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Consistency score (0-1) where 1 = fully consistent"
    )
    consistency_notes: list[str] = Field(
        default_factory=list,
        description="Notes about consistency"
    )

    # Temporal information
    established_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="When the relationship was established"
    )
    valid_from: datetime | None = Field(
        default=None,
        description="Start of relationship validity"
    )
    valid_to: datetime | None = Field(
        default=None,
        description="End of relationship validity"
    )

    # Confidence and quality
    confidence: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Confidence in this relationship"
    )

    # Provenance
    created_by: str | None = Field(default=None, description="Who created this relationship")
    source: str = Field(default="", description="Source of the relationship")

    # Additional metadata
    custom_metadata: dict[str, Any] = Field(default_factory=dict, description="Custom metadata")


class EvidenceEdge(BaseModel):
    """An edge in the evidence graph representing a relationship between nodes.

    Edges define how evidence nodes are related to each other, including:
    - Temporal relationships (occurred_before, occurred_after, overlaps)
    - Derivation relationships (derived_from, based_on)
    - Support relationships (supports, confirms, corroborates)
    - Contradiction relationships (contradicts, conflicts_with)
    - Versioning relationships (supersedes, superseded_by)
    - Clinical relationships (explains, predicts, indicates)
    """

    id: UUID = Field(default_factory=uuid4, description="Unique edge identifier")

    # Node references
    source_id: UUID = Field(default=..., description="Source node ID")
    target_id: UUID = Field(default=..., description="Target node ID")

    # Edge data
    metadata: EvidenceEdgeMetadata = Field(
        default_factory=EvidenceEdgeMetadata,
        description="Edge metadata"
    )

    # Bidirectional reference for efficient traversal
    reverse_id: UUID | None = Field(default=None, description="ID of reverse edge if exists")


