def create_evidence_node(
    cardiac_case_id: UUID,
    entity_type: str,
    entity_id: UUID,
    node_type: EvidenceNodeType,
    data: dict[str, Any] | None = None,
    summary: str = "",
    observation_time: datetime | None = None,
    source: str = "",
    confidence: float = 0.0,
    quality_score: float = 1.0,
    provenance: str = "",
    clinical_relevance: float = 1.0,
    **kwargs: Any
) -> EvidenceNode:
    """Factory function to create an evidence node."""
    metadata = EvidenceNodeMetadata(
        node_type=node_type,
        observation_time=observation_time,
        valid_from=observation_time,
        source=source,
        confidence=confidence,
        quality_score=quality_score,
        provenance=provenance,
        clinical_relevance=clinical_relevance,
        **kwargs
    )

    return EvidenceNode(
        cardiac_case_id=cardiac_case_id,
        entity_type=entity_type,
        entity_id=entity_id,
        data=data or {},
        summary=summary,
        metadata=metadata
    )


def create_evidence_edge(
    source_id: UUID,
    target_id: UUID,
    relationship: EvidenceRelationship,
    consistency_status: ConsistencyStatus = ConsistencyStatus.UNRESOLVED,
    confidence: float = 0.0,
    created_by: str | None = None,
    **kwargs: Any
) -> EvidenceEdge:
    """Factory function to create an evidence edge."""
    metadata = EvidenceEdgeMetadata(
        relationship=relationship,
        consistency_status=consistency_status,
        confidence=confidence,
        created_by=created_by,
        **kwargs
    )

    return EvidenceEdge(
        source_id=source_id,
        target_id=target_id,
        metadata=metadata
    )


def create_evidence_graph(
    cardiac_case_id: UUID,
    name: str = "",
    description: str = "",
    **kwargs: Any
) -> EvidenceGraph:
    """Factory function to create an evidence graph."""
    return EvidenceGraph(
        cardiac_case_id=cardiac_case_id,
        name=name,
        description=description,
        **kwargs
    )
