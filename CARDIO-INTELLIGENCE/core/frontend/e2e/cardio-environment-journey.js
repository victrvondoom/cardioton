async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  await page.getByTestId("cardio-intelligence").waitFor();
  await page.getByRole("textbox", { name: "Replay date · end of day UTC", exact: true }).fill("2026-08-10");
  const responsePromise = page.waitForResponse(response => response.url().includes("/environment/observations") && response.url().includes("13.0827"), { timeout: 45000 });
  await page.getByRole("button", { name: "Earth", exact: true }).click();
  const response = await responsePromise;
  assert(response.ok(), "Environmental adapter request failed");
  const data = await response.json();
  const weather = data.series.find(series => series.variable === "temperature_2m");
  const pm = data.series.find(series => series.variable === "pm2_5");
  assert(data.context_only === true && data.personal_exposure_established === false, "Clinical/environmental boundary missing");
  assert(pm.summary.hours_present === 24, "Live Chennai PM2.5 day is incomplete; do not report a complete demonstration");
  await page.getByRole("button", { name: "Load regional air layer", exact: true }).click();
  await page.getByText(/Ingested .*points available at this hour/).waitFor({ timeout: 45000 });
  const regionalCoverage = await page.getByText(/Ingested .*points available at this hour/).innerText();
  await page.screenshot({ path: "output/playwright/cardio-intelligence-globe.png", fullPage: true });
  await page.getByRole("combobox", { name: "Environmental layer", exact: true }).selectOption("temperature_2m");
  await page.getByRole("radio", { name: "Compare B", exact: true }).check();
  await page.getByRole("spinbutton", { name: "Context latitude", exact: true }).fill("28.6139");
  await page.getByRole("spinbutton", { name: "Context longitude", exact: true }).fill("77.2090");
  const comparisonPromise = page.waitForResponse(r => r.url().includes("/environment/observations") && r.url().includes("28.6139"), { timeout: 45000 });
  await page.getByRole("button", { name: "Select", exact: true }).click();
  const comparison = await (await comparisonPromise).json();
  assert(comparison.series.find(series => series.variable === "temperature_2m").unit === "°C", "Weather unit mismatch");
  await page.getByRole("button", { name: "Use text view", exact: true }).click();
  await page.getByText("ACCESSIBLE GEOGRAPHIC SUMMARY", { exact: true }).waitFor();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "output/playwright/cardio-intelligence-environment.png", fullPage: true });
  const searchPromise = page.waitForResponse(r => r.url().includes("/environment/locations"), { timeout: 45000 });
  await page.getByRole("textbox", { name: "City or country", exact: true }).fill("Chennai");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  const search = await searchPromise;
  await page.getByRole("button", { name: "Evidence alignment", exact: true }).click();
  await page.getByRole("checkbox", { name: /I consent to a temporary, local comparison/ }).check();
  await page.getByRole("region", { name: "Environmental cardiovascular context", exact: true }).waitFor();
  assert((await page.getByTestId("cardio-intelligence").innerText()).includes("Personal exposure is not documented"), "Alignment lost exposure uncertainty");
  return { date: data.date, weatherHours: weather.summary.hours_present, pm25Hours: pm.summary.hours_present, regionalCoverage, sources: data.sources.map(source => ({ provider: source.provider, status: source.status, error: source.error })), comparisonWeatherHours: comparison.series.find(series => series.variable === "temperature_2m").summary.hours_present, searchStatus: search.status(), contextualSeparation: true, mapTextAlternative: true, consentedAlignment: true };
}
