// Run through Playwright CLI `run-code` after signing into the local synthetic demo.
// Generates only fictional data and records assertions; no provider responses are mocked.
async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const result = {};
  await page.getByTestId("cardio-intelligence").waitFor();
  await page.getByRole("button", { name: "Upload Cardiovascular Report", exact: true }).click();
  await page.getByLabel("Case reference", { exact: true }).fill(`synthetic-e2e-${Date.now()}`);
  await page.getByRole("button", { name: "Use fictional LAD report", exact: true }).click();
  const report = page.locator(".ci-report").filter({ hasText: "synthetic-angiography.txt" });
  await report.getByRole("heading", { name: "LAD stenosis, 70% reported", exact: true }).waitFor();
  assert((await report.innerText()).includes("pending · documented"), "Unreviewed report was not pending");
  await report.getByRole("button", { name: "Approve finding", exact: true }).first().click();
  await report.getByText("approved · documented", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Heart + evidence", exact: true }).click();
  await page.getByRole("button", { name: "Select Left anterior descending artery: 1 approved finding", exact: true }).click();
  const source = page.getByRole("region", { name: "Anatomical evidence trace", exact: true });
  await source.getByRole("heading", { name: "LAD stenosis, 70% reported", exact: true }).waitFor();
  assert((await source.innerText()).includes("LAD stenosis, 70%."), "Source excerpt missing");
  const download = page.waitForEvent("download");
  await source.getByRole("button", { name: "Open Evidence Passport trail", exact: true }).click();
  const passport = await download;
  await passport.saveAs("output/playwright/cardio-intelligence-report-passport.json");
  result.reportApprovalAndSourceExport = true;
  await page.locator(".ci-heart").screenshot({ path: "output/playwright/cardio-intelligence-approved-heart.png" });
  await page.getByRole("button", { name: "Cross-section", exact: true }).click();
  await page.getByLabel("Section depth in generic display coordinates", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Isolate selection", exact: true }).click();
  assert(await page.getByRole("button", { name: "Isolate selection", exact: true }).getAttribute("aria-pressed") === "true", "Isolation control did not activate");
  await page.getByRole("button", { name: "Text view", exact: true }).click();
  await page.getByText("ACCESSIBLE STRUCTURE EXPLORER", { exact: true }).waitFor();
  result.sectionAndAccessibleTextView = true;
  await page.getByRole("button", { name: "Text view", exact: true }).click();
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.waitForFunction(() => [...document.querySelectorAll("button")].some(button => button.textContent === "Illustrative motion" && button.disabled));
  assert(await page.getByRole("button", { name: "Illustrative motion", exact: true }).isDisabled(), "Reduced motion did not disable motion");
  result.reducedMotion = true;
  await page.getByRole("checkbox", { name: /Load existing fictional Cardio-Hemo observations/ }).check();
  await page.getByRole("button", { name: "2026-08-10", exact: true }).click();
  await page.locator(".ci-context").getByText("0 approved mappings · 0 available reports", { exact: true }).waitFor();
  await page.getByText("EXISTING SYNTHETIC HEMODYNAMIC ENGINE / 2026-08-10T23:59:59.999999+00:00", { exact: true }).waitFor();
  const text = await page.getByTestId("cardio-intelligence").innerText();
  assert(!text.includes("LAD stenosis, 70% reported"), "Today's report leaked into August replay");
  assert(!text.includes("Observation/demo-08-10-bnp"), "Delayed BNP leaked before availability");
  result.historicalReportExclusion = true;
  await page.getByRole("button", { name: "2026-08-12", exact: true }).click();
  await page.getByText("EXISTING SYNTHETIC HEMODYNAMIC ENGINE / 2026-08-12T23:59:59.999999+00:00", { exact: true }).waitFor();
  await page.getByTestId("hemo-axis-pump_function").click();
  await page.getByRole("heading", { name: "WHY DID THIS CHANGE?", exact: true }).waitFor();
  const original = page.locator("#hemo-why").getByRole("button").filter({ hasText: "Open original record" }).first();
  await original.click();
  await page.getByText("Original record & provenance", { exact: true }).click();
  await page.getByText("Original source record", { exact: true }).waitFor();
  result.hemodynamicWhyAndOriginalSource = true;
  await page.getByRole("button", { name: "Close explanation", exact: true }).click();
  result.hemodynamicReplay = true;
  await page.getByRole("button", { name: "Evidence alignment", exact: true }).click();
  const hemoSources = page.getByText(/^Inspect \d+ existing hemodynamic source observations at 2026-08-12/);
  await hemoSources.waitFor();
  await hemoSources.click();
  await page.getByRole("table").filter({ has: page.getByText("Existing engine observations · event and availability clocks", { exact: true }) }).waitFor();
  await page.getByRole("checkbox", { name: /I consent to a temporary, local comparison/ }).check();
  await page.getByRole("region", { name: "Environmental cardiovascular context", exact: true }).waitFor();
  result.hemodynamicEnvironmentalAlignment = true;
  await page.getByRole("button", { name: "Today", exact: true }).click();
  await page.getByRole("button", { name: "Reports + review", exact: true }).click();
  await page.getByRole("button", { name: "Use fictional unresolved report", exact: true }).click();
  const unresolved = page.locator(".ci-report").filter({ hasText: "synthetic-unresolved.txt" });
  await unresolved.getByRole("heading", { name: "Cardiac disease reported; location unresolved", exact: true }).waitFor();
  assert((await unresolved.innerText()).includes("Location not established from supplied evidence"), "Generic cardiac disease invented a location");
  await unresolved.getByRole("button", { name: "Approve finding", exact: true }).click();
  await unresolved.getByText("approved · documented", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Heart + evidence", exact: true }).click();
  await page.locator(".ci-context").getByText("1 approved mappings · 2 available reports", { exact: true }).waitFor();
  await page.getByRole("heading", { name: "Location not established from supplied evidence", exact: true }).waitFor();
  result.unresolvedFindingNoInventedLesion = true;
  await page.getByRole("button", { name: "Compare", exact: true }).click();
  await page.getByLabel("Comparison date · end of day UTC", { exact: true }).fill("2026-08-10");
  assert(await page.getByRole("figure").count() === 2, "Comparison did not render two reference views");
  result.comparison = true;
  await page.getByRole("button", { name: "Heart + evidence", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  const widths = await page.evaluate(() => ({ viewport: window.innerWidth, page: document.documentElement.scrollWidth }));
  assert(widths.page <= widths.viewport + 2, `Mobile overflow ${widths.page} > ${widths.viewport}`);
  await page.screenshot({ path: "output/playwright/cardio-intelligence-mobile.png", fullPage: true });
  result.mobile = widths;
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "output/playwright/cardio-intelligence-desktop.png", fullPage: true });
  return result;
}
