class EvidenceGraph(BaseModel):
    """The complete evidence graph for a cardiac case.

    An EvidenceGraph represents all evidence related to a cardiac case and the
    relationships between them. It is the foundation of the Cardiac Evidence
    Continuity Engine.

    The graph enables:
    - Temporal alignment checking across modalities
    - Cross-modality contradiction detection
    - Provenance tracking and audit trails
    - Confidence scoring based on evidence quality and consistency
    - Digital twin state validation

    Graph Structure:
    - Nodes: EvidenceNode instances representing individual evidence items
    - Edges: EvidenceEdge instances representing relationships between evidence

    Usage:
    ```python
    graph = EvidenceGraph(cardiac_case_id=case_id)

    # Add evidence
    ecg_node = graph.add_node(entity_type="ECGStudy", entity_id=ecg_id, data=ecg_data)
    imaging_node = graph.add_node(entity_type="ImagingStudy", entity_id=cmr_id, data=cmr_data)

    # Add relationships
    graph.add_edge(ecg_node.id, imaging_node.id, relationship=EvidenceRelationship.OCCURRED_BEFORE)

    # Check consistency
    contradictions = graph.find_contradictions()
    misalignments = graph.find_temporal_misalignments()

    # Compute scores
    confidence = graph.compute_confidence_score()
    consistency = graph.compute_consistency_score()
    ```
    """

    id: UUID = Field(default_factory=uuid4, description="Unique graph identifier")
    cardiac_case_id: UUID = Field(default=..., description="Reference to CardiacCase")

    # Graph structure
    nodes: dict[UUID, EvidenceNode] = Field(
        default_factory=dict,
        description="All nodes in the graph, indexed by UUID"
    )
    edges: dict[UUID, EvidenceEdge] = Field(
        default_factory=dict,
        description="All edges in the graph, indexed by UUID"
    )

    # Indexes for efficient lookups
    node_index: dict[str, list[UUID]] = Field(
        default_factory=dict,
        description="Index of node IDs by entity type"
    )
    edge_index: dict[str, list[UUID]] = Field(
        default_factory=dict,
        description="Index of edge IDs by relationship type"
    )

    # Graph metadata
    name: str = Field(default="", description="Human-readable name for the graph")
    description: str = Field(default="", description="Description of the graph")

    # Statistics (computed on demand or cached)
    statistics: EvidenceGraphStatistics = Field(
        default_factory=EvidenceGraphStatistics,
        description="Graph statistics"
    )

    # Versioning
    version: int = Field(default=1, ge=1, description="Graph version")
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="When the graph was created"
    )
    updated_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="When the graph was last updated"
    )

    # Provenance
    created_by: str | None = Field(default=None, description="Who created the graph")
    updated_by: str | None = Field(default=None, description="Who last updated the graph")

    # Validation status
    is_valid: bool = Field(default=True, description="Whether the graph is valid")
    validation_errors: list[str] = Field(
        default_factory=list,
        description="Validation errors"
    )

    # Metadata
    custom_metadata: dict[str, Any] = Field(default_factory=dict, description="Custom metadata")


