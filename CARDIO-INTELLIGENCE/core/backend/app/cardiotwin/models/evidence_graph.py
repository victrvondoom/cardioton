"""Evidence Graph Model for Cardiac Evidence Continuity Engine.

This module defines the graph-based evidence model that tracks relationships,
consistency, and provenance across all evidence supporting a cardiac case.

The Evidence Graph provides:
- Temporal alignment of evidence across modalities
- Cross-modality contradiction detection
- Provenance tracking and audit trails
- Confidence scoring based on evidence quality and consistency
- State validation for digital twin synchronization

Key Concepts:
- EvidenceNode: A single piece of evidence (observation, measurement, prediction, etc.)
- EvidenceEdge: Relationship between evidence nodes (supports, contradicts, supersedes, etc.)
- EvidenceGraph: The complete graph of evidence for a cardiac case
- ConsistencyScore: Quantitative measure of evidence alignment
"""

from __future__ import annotations

from datetime import UTC, datetime
from enum import Enum
from typing import Any
from uuid import UUID, uuid4

from pydantic import BaseModel, Field, model_validator

# =============================================================================
# ENUMS
# =============================================================================

class EvidenceNodeType(str, Enum):
    """Types of nodes in the evidence graph."""

    # Primary data sources
    OBSERVATION = "observation"           # Clinical observation (vital signs, labs)
    ECG_STUDY = "ecg_study"               # ECG recording
    IMAGING_STUDY = "imaging_study"       # Cardiac imaging (CMR, Echo, CT, etc.)
    DIAGNOSTIC_REPORT = "diagnostic_report"  # Clinician or AI-generated report
    CLINICAL_NOTE = "clinical_note"       # Free-text clinical notes

    # AI and model outputs
    MODEL_INFERENCE = "model_inference"    # AI model prediction
    SIMULATION = "simulation"              # Digital twin simulation
    SEGMENTATION = "segmentation"         # Anatomical segmentation

    # Clinical entities
    PATIENT = "patient"                   # Patient record
    ENCOUNTER = "encounter"               # Clinical encounter

    # Composite
    DIGITAL_TWIN = "digital_twin"         # Digital twin instance
    AGENT_EXECUTION = "agent_execution"   # Multi-agent workflow execution
    CLINICAL_REVIEW = "clinical_review"   # Human review of evidence


class EvidenceRelationship(str, Enum):
    """Types of relationships between evidence nodes."""

    # Temporal relationships
    OCCURRED_AT = "occurred_at"           # Evidence was observed at a specific time
    OCCURRED_BEFORE = "occurred_before"     # Temporal ordering
    OCCURRED_AFTER = "occurred_after"       # Temporal ordering
    OVERLAPS = "overlaps"                 # Evidence time windows overlap

    # Derivation relationships
    DERIVED_FROM = "derived_from"          # Evidence was derived from source evidence
    BASED_ON = "based_on"                  # Evidence is based on other evidence
    GENERATED_BY = "generated_by"          # Evidence was generated by a process/agent

    # Support relationships
    SUPPORTS = "supports"                  # Evidence supports a conclusion
    CONFIRMS = "confirms"                  # Strong support
    CORROBORATES = "corroborates"          # Independent confirmation

    # Contradiction relationships
    CONTRADICTS = "contradicts"            # Evidence contradicts other evidence
    CONFLICTS_WITH = "conflicts_with"      # Direct conflict
    CHALLENGES = "challenges"              # Weak contradiction

    # Versioning relationships
    SUPERSEDES = "supersedes"              # New evidence replaces old
    SUPERSEDED_BY = "superseded_by"        # Old evidence replaced by new
    UPDATED_BY = "updated_by"              # Evidence was updated

    # Clinical relationships
    EXPLAINS = "explains"                  # Evidence provides explanation
    PREDICTS = "predicts"                  # Evidence predicts outcome
    INDICATES = "indicates"                # Evidence indicates finding

    # Review relationships
    REVIEWED_BY = "reviewed_by"            # Evidence was reviewed
    APPROVED_BY = "approved_by"            # Evidence was approved
    REJECTED_BY = "rejected_by"            # Evidence was rejected
    REQUIRES_REVIEW = "requires_review"    # Evidence needs review


class ConsistencyStatus(str, Enum):
    """Consistency status for evidence relationships."""

    CONSISTENT = "consistent"              # No issues detected
    MINOR_MISALIGNMENT = "minor_misalignment"  # Minor timing/value differences
    MAJOR_MISALIGNMENT = "major_misalignment"  # Significant differences
    CONTRADICTORY = "contradictory"        # Direct contradiction
    UNRESOLVED = "unresolved"              # Not yet evaluated


class ConfidenceScoringMethod(str, Enum):
    """Methods for calculating confidence scores."""

    SIMPLE_AVERAGE = "simple_average"       # Average of all evidence confidence
    WEIGHTED_AVERAGE = "weighted_average"   # Weighted by evidence quality
    SOURCE_BASED = "source_based"           # Based on source reliability
    TIME_BASED = "time_based"               # Based on recency
    COMPOSITE = "composite"                # Multi-factor composite score


